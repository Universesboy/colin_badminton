"""Website sync for colinbadminton.com.

The site is a React app whose video lists live in src/data/site.js
(highlightVideos / trainingVideos, YouTube ids + poster webp). Deploys happen
through GitHub Actions on every push to main (GitHub Pages behind Cloudflare).

So syncing = add one entry + one poster on a branch and open a pull request.
Merging the PR is the publish step (Colin's decision). `cba site-check` then
verifies the live site after the deploy.
"""
from __future__ import annotations

import re
import shutil
import subprocess
import urllib.request

from . import config

SITE_JS = config.REPO_ROOT / "src" / "data" / "site.js"


def _js_str(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"


def entry_js(youtube_id: str, poster_name: str, title: str, description: str, category: str | None,
             orientation: str) -> str:
    lines = ["  {", f"    id: {_js_str(youtube_id)},", f"    poster: thumb({_js_str(poster_name)}),",
             f"    title: {_js_str(title)},", f"    description: {_js_str(description)},"]
    if category:
        lines.append(f"    category: {_js_str(category)},")
    lines += [f"    orientation: {_js_str(orientation)},", "  },"]
    return "\n".join(lines)


def add_video(job, youtube_id: str, orientation: str) -> dict:
    copy = job.read_json("copy.json")["website"]
    section = "trainingVideos" if copy.get("section") == "training" else "highlightVideos"
    src = SITE_JS.read_text("utf-8")
    if f"id: '{youtube_id}'" in src:
        return {"changed": False, "reason": "video already on the site (duplicate check)"}
    poster_name = f"cba-{job.id}"
    shutil.copy2(job.dir / "covers" / "site_poster.webp",
                 config.REPO_ROOT / "public" / "media" / "thumbs" / f"{poster_name}.webp")
    entry = entry_js(youtube_id, poster_name, copy["title"], copy["description"],
                     copy.get("category") if section == "highlightVideos" else None, orientation)
    marker = f"export const {section} = ["
    if marker not in src:
        raise RuntimeError(f"{marker!r} not found in site.js; the site structure changed")
    src = src.replace(marker, marker + "\n" + entry, 1)
    SITE_JS.write_text(src, "utf-8")
    return {"changed": True, "section": section, "poster": f"public/media/thumbs/{poster_name}.webp",
            "seo_title": copy.get("seo_title"), "seo_description": copy.get("seo_description")}


def open_pr(job, youtube_id: str, info: dict) -> str:
    branch = f"content/{job.id}"
    run = lambda *c: subprocess.run(c, cwd=config.REPO_ROOT, check=True, capture_output=True, text=True).stdout
    run("git", "checkout", "-B", branch)
    run("git", "add", "src/data/site.js", info["poster"])
    run("git", "commit", "-m", f"Add video {youtube_id} to {info['section']} ({job.id})")
    run("git", "push", "-u", "origin", branch)
    body = (f"Adds YouTube video `{youtube_id}` to `{info['section']}` with poster `{info['poster']}`.\n\n"
            f"Generated by the content agent from job `{job.id}`. Merging deploys colinbadminton.com via GitHub Pages.")
    return run("gh", "pr", "create", "--title", f"Add video: {job.read_json('copy.json')['website']['title']}",
               "--body", body, "--head", branch).strip()


def check_live(youtube_id: str) -> dict:
    """Post-deploy check: page answers, bundle contains the video, video is embeddable."""
    out = {}

    def get(url):
        req = urllib.request.Request(url, headers={"User-Agent": "cba-site-check"})
        with urllib.request.urlopen(req, timeout=20) as r:
            return r.status, r.read().decode("utf-8", "replace")
    for path in ("/", "/highlights", "/training"):
        try:
            out[path] = get(config.SITE_URL + path)[0]
        except Exception as e:  # noqa: BLE001
            out[path] = f"error: {e}"
    try:
        _, home = get(config.SITE_URL + "/")
        js = re.search(r'src="(/static/js/main\.[^"]+\.js)"', home)
        bundle = get(config.SITE_URL + js.group(1))[1] if js else ""
        out["in_bundle"] = youtube_id in bundle
        out["duplicate_count"] = bundle.count(youtube_id)
    except Exception as e:  # noqa: BLE001
        out["in_bundle"] = f"error: {e}"
    try:
        out["embeddable"] = get("https://www.youtube.com/oembed?format=json&url=https://www.youtube.com/watch?v="
                                + youtube_id)[0] == 200
    except Exception as e:  # noqa: BLE001
        out["embeddable"] = f"error: {e}"
    return out
